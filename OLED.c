void PutPixel(unsigned int x, unsigned int y)
{
    unsigned int r,b;
    char c;

	if(x<128) 
	 if(y<64) 
	  {
      r = y >> 3; //numarul randului
      b = y & 0x07; //numarul bitului
      c = 1 << b; //MascaBit[b];
      LCDBuff[r][x] |= c;
	  }
}
void PutImage(const unsigned char *image)
    {
    unsigned int x,y;

    for (x=0;x<128;x++)
	  for(y=0;y<8;y++)
        {
        LCDBuff[y][x] = image[x+y*128];
        }
    }

void PutLine(int x0, int y0, int x1, int y1)
    {
    int dy = y1 - y0;
    int dx = x1 - x0;
    float t = (float) 0.5;                      // offset for rounding

    PutPixel(x0, y0);

    //if (Math.abs(dx) > Math.abs(dy))
    if ((dx >= 0 ? dx : (-1)*dx) > (dy >= 0 ? dy : (-1)*dy))
        {                                       // slope < 1
        float m = (float) dy / (float) dx;      // compute slope
        t += y0;
        dx = (dx < 0) ? -1 : 1;
        m *= dx;
        while (x0 != x1)
            {
            x0 += dx;                           // step to next x value
            t += m;                             // add slope to y value
            PutPixel(x0, (int) t);
            }
        }
    else
        {                                       // slope >= 1
        float m = (float) dx / (float) dy;      // compute slope
        t += x0;
        dy = (dy < 0) ? -1 : 1;
        m *= dy;
        while (y0 != y1)
            {
            y0 += dy;                           // step to next y value
            t += m;                             // add slope to x value
            PutPixel((int) t, y0);
            }
        }
    }
void PutVerticalLine(unsigned char x, unsigned char y0, unsigned char y1)
    {
    unsigned char i;

    if (x < 128 && y0 < 64 && y1 < 64)
        {
        if (y0 < y1)
            {
            for (i = y0; i <= y1; i++)
                {
                PutPixel(x, i);
                }
            }
        else
            {
            for (i = y1; i <= y0; i++)
                {
                PutPixel(x, i);
                }
            }
        }
    }
void PutHorizontalLine(unsigned char x0, unsigned char x1, unsigned char y)
    {
    unsigned char i;

    if (x0 < 128 && x1 < 128 && y < 64)
        {
        if (x0 < x1)
            {
            for (i = x0; i <= x1; i++)
                {
                PutPixel(i, y);
                }
            }
        else
            {
            for (i = x1; i <= x0; i++)
                {
                PutPixel(i, y);
                }
            }
        }
    }

