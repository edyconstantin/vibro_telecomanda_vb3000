// (incrementa i, nu j) - inversa doar 8 pixeli, nu toata pagina.
void invert_lcd(void)
    {
    int i,j;
    for (i = 0; i < 8; i++)
      for (j = 0; j < 128; j++)
        {
        LCDBuff[i][j] ^= 0xff;
        }
    LCD_MarkAll();
    }

